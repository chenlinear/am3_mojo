def threshold(r):
    """The photon energy [GeV] at the threshold of reaction r (the README's s = (m_Y + m_K)^2)."""
    mN, mY, mK, _ = REACTIONS[r]
    return float(readme.photon_threshold()(mN, mY + mK))


def kin_chi(r, E, cos):
    """The README's chi of reaction r at photon energy E [GeV] (above its threshold) for <cos theta_K>."""
    mN, mY, mK, _ = REACTIONS[r]
    with np.errstate(invalid='ignore'):
        return readme.numeric_chi()(mN, mY, mK, np.asarray(E, float), cos)


def _points(r):
    P = np.concatenate([np.array(p) for _, p in DATA[r]])
    return P[np.argsort(P[:, 0])]


def _measured(r, E, col):
    """Mean over the data sets of their linear interpolation (NaN outside)."""
    V = np.array([np.interp(E, np.array(p)[:, 0], np.array(p)[:, col], left=np.nan, right=np.nan)
                  for _, p in DATA[r]])
    n = np.sum(~np.isnan(V), axis=0)
    with np.errstate(invalid='ignore'):
        return np.where(n > 0, np.nansum(V, axis=0) / np.maximum(n, 1), np.nan)


def power_law(r):
    """sigma of r above all its data: (exponent n, ln A) of A E^n fitted to its last GeV of data, and the points fitted."""
    P = _points(r)
    top = P[P[:, 0] > P[-1, 0] - 1.0]
    n, lnA = np.polyfit(np.log(top[:, 0]), np.log(top[:, 1]), 1)
    return n, lnA, top


def analogue_factor(r):
    """The factor by which r follows its analogous gamma p reaction above its data: the ratio of their mean cross
    sections over the last 0.6 GeV of r's data (all of them if they span less)."""
    P = _points(r)
    win = np.linspace(max(P[0, 0], P[-1, 0] - 0.6), P[-1, 0], 61)
    return np.mean(_measured(r, win, 1)) / np.mean(sigma(REACTIONS[r][3], win))


def _beyond_all(r, E, col):
    """Above the data of r: last-0.4-GeV mean of <cos> (col 2), power law of sigma (col 1)."""
    if col == 2:
        P = _points(r)
        top = P[P[:, 0] > P[-1, 0] - 0.4]
        return np.full_like(E, np.average(top[:, 2], weights=top[:, 1]))
    n, lnA, _ = power_law(r)
    return np.exp(lnA) * E ** n


def cos_theta(r, E):
    """<cos theta_K> of reaction r at photon energies E."""
    c = _measured(r, E, 2)
    P = _points(r)
    c = np.where(np.isnan(c) & (E < P[0, 0]), P[0, 2], c)
    sub = REACTIONS[r][3]
    if sub is not None:
        c = np.where(np.isnan(c), cos_theta(sub, E), c)
    return np.where(np.isnan(c), _beyond_all(r, E, 2), c)


def sigma(r, E):
    """Cross section [mubarn] of reaction r at photon energies E."""
    s = _measured(r, E, 1)
    P = _points(r)
    th = threshold(r)
    s = np.where(np.isnan(s) & (E < P[0, 0]), np.maximum(P[0, 1] * (E - th) / (P[0, 0] - th), 0.0), s)
    s = np.where(E <= th, 0.0, s)
    sub = REACTIONS[r][3]
    if sub is not None:
        s = np.where(np.isnan(s), analogue_factor(r) * sigma(sub, E), s)
    return np.where(np.isnan(s), _beyond_all(r, E, 1), s)


def step_chi(column, step, isotropic=False):
    """Cross-section-weighted chi of a channel column over a step (NaN if
    the column has no cross section there); isotropic: for <cos theta> = 0."""
    a, b = STEPS[step]
    E = np.linspace(a, b, 2001)
    num = den = 0.0
    for r in COLUMNS[column]:
        s = sigma(r, E)
        x = np.where(s > 0, kin_chi(r, E, 0 * E if isotropic else cos_theta(r, E)), 0.0)
        num += np.trapezoid(s * x, E)
        den += np.trapezoid(s, E)
    return num / den if den > 0 else np.nan


def step_sigma(r, step):
    """Mean cross section [mubarn] of reaction r over a step."""
    a, b = STEPS[step]
    E = np.linspace(a, b, 2001)
    return np.trapezoid(sigma(r, E), E) / (b - a)


def column_sigma(column, step):
    """Step cross section [mubarn] of a channel column."""
    return sum(step_sigma(r, step) for r in COLUMNS[column])


def steps_table():
    """{column: [(step cross section [mubarn], step chi) for every step]}: the steps of the code's two-body channels."""
    return {c: [(column_sigma(c, i), step_chi(c, i)) for i in range(len(STEPS))] for c in COLUMNS}
