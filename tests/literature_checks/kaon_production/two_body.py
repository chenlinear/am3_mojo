"""Photo-hadronic kaons: the two-body channels gamma N -> K Lambda, K Sigma (README "Production in photo-hadronic
interactions") from tests/support/measured/ky_angular.py, the cross section and mean CM angle of the kaon per energy
bin of the published data (regenerated by tools/ky_angular_extract.py).
  1. The steps of the code's table: sigma and chi of every channel column, chi against its isotropic value (README:
     p -> K+ 5 % below it near threshold and by more than half at 3-5 GeV; n -> K0 7-8 % above it below 1.25 GeV),
     and <cos theta> of K+ Lambda near threshold and at 3.5 GeV.
  2. The data and beyond: the range of every data set (README table of the data), the power laws of K+ Lambda and
     K+ Sigma0 above all data (README: E^-2.7, E^-2.9), and the scale factors of the analogous gamma p reactions
     above a reaction's data (README: 0.21, 0.15, 2.0, 1.7). n -> K0 with the factor 0.5 of pure K* exchange for
     K0 Sigma0 (README: up to 40 % lower above 1.65 GeV).
  3. The experiments against each other. SAPHIR and CLAS in <cos theta> at 1.6-2.4 GeV (README: up to 0.15 for
     K+ Lambda and 0.18 for K+ Sigma0, chi uncertain by about +-0.02). p -> K0 above 2.2 GeV with the angular
     distribution of K+ Sigma0 for SAPHIR's sparse K0 Sigma+ bins (README: about +-0.04). CLAS's K+ Lambda 27-39 %
     above SAPHIR's at 1.25-1.9 GeV (over SAPHIR's bins), its K0 Lambda 1.25-2.2 times A2's below 1.25 GeV. The
     steps with one experiment alone where two measured a reaction (README: p -> K+ up to 11 % at 1.05-3.0 GeV;
     n -> K0 -29 ... +42 % and +-17 % in the first two steps).
The script does not read the code: tests/unit/test_kaon_channels.py compares the code's table with these values.
derivations/kaon_production.py compares Hümmer et al.'s K+ channel with the README's steps (17 % more
int sigma d eps_r over 0.91-1.65 GeV) and derives the constants of its response function from their eq. 27."""
import os
import sys
import numpy as np

sys.path.insert(1, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))   # tests/
from support.measured import ky_angular as K  # noqa: E402
from support.paths import load_derivation  # noqa: E402

derivation = load_derivation('kaon_production')   # the factor of pure K* exchange

COL = list(K.COLUMNS)
ORIG = {r: list(v) for r, v in K.DATA.items()}


REACTIONS_SUB = {r: v[3] for r, v in K.REACTIONS.items() if v[3] is not None}

print('1. The steps: sigma [mubarn], chi, its isotropic value and their ratio')
T = K.steps_table()
for i, (a, b) in enumerate(K.STEPS):
    cells = []
    for c in COL:
        s, x = T[c][i]
        iso = K.step_chi(c, i, isotropic=True)
        cells.append(f'{c} {s:6.3f} {x:.3f} (iso {iso:.3f}, ratio {x / iso:.3f})' if s > 0 else f'{c}  -')
    print(f'  {a:.2f}-{b:.2f} GeV: ' + ';  '.join(cells))
E = np.linspace(*K.STEPS[0], 2001)
s = K.sigma('K+L', E)
print(f'  K+ Lambda <cos theta>: {np.trapezoid(s * K.cos_theta("K+L", E), E) / np.trapezoid(s, E):+.3f} in the first step'
      f' (sigma-weighted), {K.cos_theta("K+L", np.array([3.5]))[0]:+.2f} at 3.5 GeV')

print('\n2. The data and beyond: the range of every data set [GeV, first and last bin centre]')
for r, sets in K.DATA.items():
    print(f'  {r:5s} (threshold {K.threshold(r):.3f}): '
          + ';  '.join(f'{name} {pts[0][0]:.3f}-{pts[-1][0]:.3f}' for name, pts in sets))
print('  above all data: power laws fitted to the last GeV of data (as in K.sigma)')
for r in ('K+L', 'K+S0'):
    n, _, top = K.power_law(r)
    print(f'  {r:5s} ~ E^{n:.2f} (fitted to {top[0, 0]:.2f}-{top[-1, 0]:.2f} GeV)')
print('  above their data: scale factors of the analogous gamma p reactions, the ratios of the mean cross sections'
      ' over the last 0.6 GeV of data')
for r, sub in REACTIONS_SUB.items():
    P = K._points(r)
    print(f'  {r:5s} = {K.analogue_factor(r):.4f} x {sub:5s} (data up to {P[-1, 0]:.3f} GeV; ratio over '
          f'{max(P[0, 0], P[-1, 0] - 0.6):.3f}-{P[-1, 0]:.3f} GeV)')
k, kstar = K.analogue_factor('K0S0'), float(derivation.readme_kstar_factor())
print(f'  n -> K0 with K0 Sigma0 = {kstar:g} x K0 Sigma+ (pure K* exchange) instead of {k:.3f} x:')
for i, (a, b) in enumerate(K.STEPS):
    if a >= 1.6:
        s0, s1 = K.step_sigma('K0L', i), K.step_sigma('K0S0', i)
        print(f'    {a:.2f}-{b:.2f} GeV: {(s0 + s1 * kstar / k) / (s0 + s1) - 1:+.1%}')

print('\n3. The experiments against each other')
for r in ('K+L', 'K+S0'):
    S, C = (np.array(ORIG[r][k][1]) for k in (0, 1))
    E = np.linspace(1.6, 2.4, 8001)
    d = np.interp(E, S[:, 0], S[:, 2]) - np.interp(E, C[:, 0], C[:, 2])
    i = np.argmax(np.abs(d))
    dchi = K.kin_chi(r, E[i], 0.0) - K.kin_chi(r, E[i], 1.0)
    print(f'  {r}: SAPHIR - CLAS in <cos theta> at 1.6-2.4 GeV up to {d[i]:+.3f} (at {E[i]:.3f} GeV; half of it in chi:'
          f' {abs(d[i]) * dchi / 2:.3f})')
S, C = (np.array(ORIG['K+L'][k][1]) for k in (0, 1))
ratios = [np.mean(np.interp(np.linspace(e - 0.025, e + 0.025, 501), C[:, 0], C[:, 1])) / s - 1
          for e, s, _ in S if 1.25 < e < 1.9 and e - 0.025 >= C[0, 0]]
print(f'  K+ Lambda, CLAS averaged over SAPHIR\'s bins at 1.25-1.9 GeV: {min(ratios):+.1%} ... {max(ratios):+.1%} against SAPHIR')
C, A = (np.array(ORIG['K0L'][k][1]) for k in (0, 1))
E = np.linspace(0.97, 1.25, 2801)
q = np.interp(E, C[:, 0], C[:, 1]) / np.interp(E, A[:, 0], A[:, 1])
print(f'  K0 Lambda below 1.25 GeV, CLAS / A2: {q.min():.2f} ... {q.max():.2f}')
for label, keep in (('SAPHIR', 0), ('CLAS', 1)):
    K.DATA['K+L'], K.DATA['K+S0'] = [ORIG['K+L'][keep]], [ORIG['K+S0'][keep]]
    alt = [K.column_sigma('p->K+', i) for i in range(len(K.STEPS))]
    K.DATA.update({r: ORIG[r] for r in ('K+L', 'K+S0')})
    print(f'  p -> K+ with {label} alone for K+ Lambda and K+ Sigma0: ' + ', '.join(
        f'{a:.2f}-{b:.2f} {alt[i] / T["p->K+"][i][0] - 1:+.1%}' for i, (a, b) in enumerate(K.STEPS)))
# p -> K0 above 2.2 GeV rests on SAPHIR's sparse K0 Sigma+ bins: chi with the angular distribution of K+ Sigma0
P = ORIG['K0S+'][0][1]
K.DATA['K0S+'] = [(ORIG['K0S+'][0][0], [(e, s, float(K.cos_theta('K+S0', np.array([e]))[0]) if e > 2.2 else c)
                                        for e, s, c in P])]
alt = [K.step_chi('p->K0', i) for i in range(len(K.STEPS))]
K.DATA['K0S+'] = ORIG['K0S+']
print('  p -> K0 chi with the <cos theta> of K+ Sigma0 for the K0 Sigma+ bins above 2.2 GeV: ' + ', '.join(
    f'{a:.2f}-{b:.2f} {alt[i] - T["p->K0"][i][1]:+.3f}' for i, (a, b) in enumerate(K.STEPS) if a >= 1.6))
for label, keep in (('CLAS', 0), ('A2', 1)):
    K.DATA['K0L'] = [ORIG['K0L'][keep]]
    alt = [K.column_sigma('n->K0', i) for i in range(2)]
    K.DATA['K0L'] = ORIG['K0L']
    print(f'  n -> K0 with {label} alone for K0 Lambda: ' + ', '.join(
        f'{a:.2f}-{b:.2f} {alt[i] / T["n->K0"][i][0] - 1:+.1%}' for i, (a, b) in enumerate(K.STEPS[:2])))
