"""Write src/am3_mojo/physics/triplet_tables.mojo from the Monte Carlo tables (produce.py).

usage: python make_tables.py TABLE_DIR OUT.mojo
For every k node: sigma / (alpha r_e^2) and the per-interaction distributions dN/dln y of the three products
(see the header it writes), on tpp_nbins(k) = floor((ln k + 0.1 - LY0)/DLY) + 1 bins, as in physics/triplet.mojo, which
fits to these tables the asymptotic laws it uses above the last node.
"""
import glob, os, sys
import numpy as np

LY0, DLY = -0.85, 0.05


def tpp_nbins(k):
    return int(np.floor((np.log(k) + 0.1 - LY0) / DLY)) + 1


def load(d):
    rows = []
    for fn in glob.glob(os.path.join(d, 'k_*.npz')):
        z = np.load(fn)
        rows.append({key: z[key] for key in z.files})
    rows.sort(key=lambda r: float(r['k']))
    return rows


def string_literal(name, values, per_line=12):
    toks = [f'{x:.6g}' for x in values]
    lines = [' '.join(toks[i:i + per_line]) + ' ' for i in range(0, len(toks), per_line)]
    body = '\n'.join(f'    "{l}"' for l in lines)
    return f'comptime {name} = (\n{body}\n)\n'


def main(d, out):
    rows = load(d)
    ks = np.array([float(r['k']) for r in rows])
    sig = np.array([float(r['sig']) for r in rows])
    dist = []
    info = []
    for row in rows:
        k = float(row['k'])
        nb = tpp_nbins(k)
        dd = np.zeros((3, nb))
        src = row['dist']
        n = min(nb, src.shape[1])
        dd[:, :n] = src[:, :n]
        if src.shape[1] > nb and np.any(src[:, nb:] > 0):
            raise RuntimeError(f'k={k}: weight beyond tpp_nbins')
        dd = np.maximum(dd, 0.0)
        ly = LY0 + (np.arange(nb) + 0.5) * DLY
        for r in range(3):
            dd[r] /= dd[r].sum() * DLY
        means = [np.sum(dd[r] * np.exp(ly)) * DLY / k for r in range(3)]
        info.append((k, means, row['means']))
        dist.append(dd.ravel())
    src = f'''"""Tables of triplet pair production, generated by tools/triplet/make_tables.py.

Do not edit. Monte Carlo integrals of the lowest-order QED matrix element
(tools/triplet/produce.py):
  k: photon energy in the rest frame of the target lepton [m_e c^2]
  TPP_SIG: sigma(k) / (alpha r_e^2)
  TPP_DIST: for every k, dN/dln y per interaction of the positron
    (y = x+ k), the lower-energy electron (y = x_low k) and the recoil
    (y = xi k, xi = 1 - x_high), tpp_nbins(k) bins each from ln y = TPP_LY0
    in steps TPP_DLY
"""

comptime TPP_LY0: Float64 = {LY0}
comptime TPP_DLY: Float64 = {DLY}

'''
    src += string_literal('TPP_K', ks) + '\n'
    src += string_literal('TPP_SIG', sig) + '\n'
    src += string_literal('TPP_DIST', np.concatenate(dist))
    open(out, 'w').write(src)
    print(f'{len(ks)} nodes, {sum(len(x) for x in dist)} values -> {out} ({len(src) / 1e3:.0f} kB)')
    for k, m, mm in info:
        print(f'  k={k:<10.6g} table means {m[0]:.6g} {m[1]:.6g} {m[2]:.6g}  MC {mm[0]:.6g} {mm[1]:.6g} {mm[2]:.6g}  '
              f'xi-(x+ + x_low) {m[2]-m[0]-m[1]:+.1e}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
